ALTER TABLE public.portifolio ADD COLUMN IF NOT EXISTS id_estilo INTEGER;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'fk_portifolio_estilo' AND conrelid = 'public.portifolio'::regclass) THEN
    ALTER TABLE public.portifolio ADD CONSTRAINT fk_portifolio_estilo FOREIGN KEY (id_estilo) REFERENCES public.estilo(id_estilo) ON DELETE SET NULL;
  END IF;
END $$;

ALTER TABLE public.estilo ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='estilo' AND policyname='Leitura publica de estilos') THEN
    CREATE POLICY "Leitura publica de estilos" ON public.estilo FOR SELECT TO anon, authenticated USING (true);
  END IF;
END $$;
GRANT SELECT ON public.estilo TO anon, authenticated;

ALTER TABLE public.seguidores ENABLE ROW LEVEL SECURITY;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='seguidores' AND policyname='Leitura publica de seguidores') THEN
    CREATE POLICY "Leitura publica de seguidores" ON public.seguidores FOR SELECT TO anon, authenticated USING (true);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='seguidores' AND policyname='Usuario ativo pode seguir') THEN
    CREATE POLICY "Usuario ativo pode seguir" ON public.seguidores FOR INSERT TO authenticated WITH CHECK (
      id_seguidor <> id_seguindo
      AND EXISTS (SELECT 1 FROM public.usuario u WHERE u.id_usuario=seguidores.id_seguidor AND u.id_auth=auth.uid())
      AND EXISTS (
        SELECT 1 FROM public.artista a JOIN public.usuario u ON u.id_usuario=a.id_usuario
        WHERE u.id_usuario=seguidores.id_seguindo AND u.status_conta='Ativo'
      )
    );
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE schemaname='public' AND tablename='seguidores' AND policyname='Usuario ativo pode deixar de seguir') THEN
    CREATE POLICY "Usuario ativo pode deixar de seguir" ON public.seguidores FOR DELETE TO authenticated USING (
      EXISTS (SELECT 1 FROM public.usuario u WHERE u.id_usuario=seguidores.id_seguidor AND u.id_auth=auth.uid())
    );
  END IF;
END $$;
